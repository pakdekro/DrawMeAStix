"""Distills ISO 3166-1 into the country list the location field suggests.

Why a dataset at all: a `location` identifier is derived from the NAME, not
from the country code (see docs/identifiers.md). "FR", "France" and "French
Republic" are therefore three distinct objects that will never merge, here or
in the platform that reads the bundle. Suggesting one canonical name is the
whole point of the list; the alpha-2 code fills the `country` property the
spec asks for.

Source: the `iso-codes` package, which tracks the standard and ships it as
JSON. It is read from the system rather than fetched: the list is a standard,
not a feed, and it changes about once a decade.

    sudo apt install iso-codes

Usage: cd backend && uv run python scripts/build_countries_dataset.py
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

SOURCE = Path("/usr/share/iso-codes/json/iso_3166-1.json")
OUT = Path(__file__).resolve().parents[2] / "frontend" / "public" / "countries.json"


def package_version() -> str:
    """Version of the iso-codes package, so the shipped file says what it is."""
    try:
        out = subprocess.run(  # noqa: S603
            ["/usr/bin/dpkg-query", "-W", "-f=${Version}", "iso-codes"],
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip() or "unknown"
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main() -> None:
    if not SOURCE.exists():
        raise SystemExit(
            f"{SOURCE} is missing. On Debian and Ubuntu: sudo apt install iso-codes"
        )
    raw = json.loads(SOURCE.read_text(encoding="utf-8"))["3166-1"]
    # `name` is the short form ("France"), which is what a platform stores and
    # what an analyst types. `official_name` ("French Republic") is deliberately
    # left out: two names for one country would defeat the purpose.
    entries = sorted(
        ({"code": c["alpha_2"], "name": c["name"]} for c in raw),
        key=lambda c: c["name"],
    )
    payload = {
        "_comment": "Generated by backend/scripts/build_countries_dataset.py - do not edit.",
        "source": f"iso-codes {package_version()}",
        "entries": entries,
    }
    OUT.write_text(
        json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + "\n",
        encoding="utf-8",
    )
    print(f"{OUT}: {len(entries)} countries")


if __name__ == "__main__":
    main()
