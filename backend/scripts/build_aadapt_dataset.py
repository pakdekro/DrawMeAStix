"""Distills MITRE AADAPT (digital asset payment technologies) into a palette dataset.

AADAPT is adversary behaviour against digital asset payment systems: exchanges,
wallets, consensus, bridges. It matters here because it starts where F3 stops:
the fraud matrix ends at Monetization with "Convert to Cryptocurrency", and
AADAPT's own eleventh tactic is called Fraud.

Structurally it is a hybrid of the two frameworks already shipped, which is why
this script borrows from both:

- its TACTICS are ATT&CK's, by identifier, ten of eleven (TA0043, TA0042,
  TA0001…), the way six of F3's eight are. Costs us nothing, since nothing in
  this application creates tactic objects;
- its TECHNIQUES are all its own, `ADT3xxx` for what it discovered and
  `ADT1xxx` for what it adapted from an ATT&CK technique of the same number.
  Four of the 68 carry an `ATT&CK-reference`, which is recorded and never
  written into a bundle: adapting `T1195` is not being `T1195`, the same rule
  ATLAS taught us.

Source: `adapt-data/dist/AADAPT.yaml` in mitre/AADAPT, the distribution copy.
The website serves a second copy at its root which trails it (66 techniques
against 68 at the time of writing), so the repository wins.

NO VERSION IS PUBLISHED, and the one in the file is a trap: AADAPT is built on
a fork of the ATLAS tooling, and `version: 4.4.0` is ATLAS's data version from
April 2023, carried over with its CHANGELOG and its LICENSE. The repository has
no tags and no releases. So this dataset ships without a version rather than
with a wrong one, and the palette shows none.

Licence: Apache 2.0 (adapt-data/LICENSE), public release unlimited, MITRE
AADAPT is a trademark of The MITRE Corporation, case number 25-1204.

Usage: cd backend && uv run python scripts/build_aadapt_dataset.py
"""

from __future__ import annotations

import json
import re
import urllib.request
from pathlib import Path

import yaml

URL = "https://raw.githubusercontent.com/mitre/AADAPT/main/adapt-data/dist/AADAPT.yaml"
# Their `ATT&CK-reference` repeats the AADAPT identifier in its `id` field, so
# the ATT&CK number is only readable from the url.
ATTACK_URL = re.compile(r"/techniques/(T\d{4}(?:\.\d{3})?)/?")
ROOT = Path(__file__).resolve().parents[2] / "frontend" / "public"
OUT = ROOT / "aadapt-dataset.json"


def shortname(name: str) -> str:
    """Tactic short name, ATT&CK style, as for the other frameworks."""
    return name.lower().replace(" ", "-")


def main() -> None:
    req = urllib.request.Request(URL, headers={"User-Agent": "drawmeastix-dataset/1.0"})
    with urllib.request.urlopen(req) as resp:  # noqa: S310
        data = yaml.safe_load(resp)

    matrix = data["matrices"][0]
    tactics = [
        {
            "id": t["id"],
            "shortname": shortname(t["name"]),
            "name": t["name"],
            # Ten of the eleven ARE ATT&CK tactics rather than mirrors of one,
            # so the identifier is the whole statement.
            "framework": "mitre-attack" if t["id"].startswith("TA") else "mitre-aadapt",
        }
        for t in matrix["tactics"]
    ]
    by_id = {t["id"]: t["shortname"] for t in tactics}

    entries = []
    adapted = 0
    for obj in matrix["techniques"]:
        entry = {
            "type": "attack-pattern",
            "id": obj["id"],
            "name": obj["name"],
            "framework": "mitre-aadapt",
        }
        phases = sorted(by_id[t] for t in obj.get("tactics", []) if t in by_id)
        if phases:
            entry["tactics"] = phases
        reference = (obj.get("ATT&CK-reference") or {}).get("url", "")
        match = ATTACK_URL.search(reference)
        if match:
            entry["attack"] = match.group(1)
            adapted += 1
        entries.append(entry)

    entries.sort(key=lambda e: e["id"])
    payload = {
        "_comment": "Generated by build_aadapt_dataset.py - do not edit.",
        "source": "MITRE AADAPT (mitre/AADAPT, adapt-data/dist/AADAPT.yaml), Apache-2.0",
        "tactics": tactics,
        "entries": entries,
    }
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8")

    subs = sum(1 for e in entries if "." in e["id"])
    own = sum(1 for t in tactics if t["framework"] == "mitre-aadapt")
    size_kb = OUT.stat().st_size // 1024
    print(
        f"AADAPT : {len(entries)} techniques ({subs} sub-techniques), "
        f"{len(tactics)} tactics -> {OUT.name} ({size_kb} Ko)"
    )
    print(f"  {len(tactics) - own} of the tactics ARE ATT&CK tactics, {own} is its own")
    print(f"  {adapted} techniques adapt an ATT&CK technique, and keep their own number")
    print("  no version published: the 4.4.0 in the file is ATLAS's, inherited by the fork")


if __name__ == "__main__":
    main()
